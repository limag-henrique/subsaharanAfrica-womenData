def get_column_label(table: str, column: str) -> str:
    table_labels = COLUMN_LABELS.get(table, {})
    if column in table_labels:
        return table_labels[column]
    common = COLUMN_LABELS.get("__common__", {})
    if column in common:
        return common[column]
    # Fallback to other tables in COLUMN_LABELS
    for other_table, other_labels in COLUMN_LABELS.items():
        if other_table != table and column in other_labels:
            return other_labels[column]
    return column


def get_value_label(column: str, value):
    if value is None:
        return None
    col_map = VALUE_MAPS.get(column)
    if not col_map:
        return value
    if value in col_map:
        return col_map[value]
    # Try integer lookup if value is string or float
    try:
        val_int = int(value)
        if val_int in col_map:
            return col_map[val_int]
    except (ValueError, TypeError):
        pass
    # Try string lookup
    val_str = str(value)
    if val_str in col_map:
        return col_map[val_str]
    return value


def get_all_column_labels(table: str, columns: list) -> dict:
    return {col: get_column_label(table, col) for col in columns}


def get_coded_columns() -> set:
    return set(VALUE_MAPS.keys())
